// Compiles the Tailwind CSS v4 entries under src/styles into generated JS modules exporting the stylesheet as a
// string:
//
//   tessel.css  -> tailwind.generated.js   adopted into every component's shadow root (core/base-element.js)
//   light.css   -> light.generated.js      light-DOM rules for slotted content, e.g. <tsl-table> (components/table.js)
//   gallery/gallery.css -> gallery/gallery.generated.css   the demo app's own layout utilities (plain stylesheet)
//
//   node scripts/build-css.js          one-off build (also run by `npm run build`)
//   node scripts/build-css.js --watch  rebuild on change while developing components
//
// Two Shadow DOM fixes are applied on top of the plain Tailwind output:
//   * `@property` registrations are ignored inside shadow roots, so utilities that read `--tw-*` defaults
//     (box-shadow, ring, transform, gradients, ...) would see no initial value. Each one is re-emitted as
//     a plain custom-property declaration on the sheet's root selector.
//   * Tailwind's `@layer properties` fallback is guarded by `@supports`, which is true here, so it is dropped.

import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync, watch, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const styles = path.join(root, 'src', 'styles');
const TARGETS = [
  { input: 'tessel.css', output: 'tailwind.generated.js', scope: '*,::before,::after,::backdrop' },
  { input: 'light.css', output: 'light.generated.js', scope: 'tsl-table,tsl-table *' },
];
const GALLERY = { input: path.join(root, 'gallery', 'gallery.css'), output: path.join(root, 'gallery', 'gallery.generated.css') };
const cli = path.join(path.dirname(createRequire(import.meta.url).resolve('@tailwindcss/cli/package.json')), 'dist', 'index.mjs');

function toShadowSafe(css, scope) {
  const defaults = [];
  css = css.replace(/@property\s+(--tw-[\w-]+)\s*\{([^}]*)\}/g, (_, name, body) => {
    const initial = /initial-value\s*:\s*([^;}]+)/.exec(body);
    if (initial) defaults.push(`${name}:${initial[1].trim()}`);
    return '';
  });
  // Tailwind's own fallback block: `@layer properties{@supports (...){*,:before,:after,::backdrop{--tw-x:initial;...}}}`.
  css = css.replace(/@layer properties\s*\{(?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*\}/g, '');
  // Must live in the base layer: unlayered rules beat every layered utility, so unlayered defaults would
  // override e.g. `-translate-y-1/2`'s own `--tw-translate-y`. The layer order is restated first so this
  // block can come before Tailwind's own `@layer` statement.
  const props = defaults.length ? `@layer theme,base,components,utilities;@layer base{${scope}{${defaults.join(';')}}}` : '';
  return props + css;
}

function writeModule(css, target) {
  const body = toShadowSafe(css, target.scope).trim();
  const js =
    `// GENERATED by scripts/build-css.js from src/styles/${target.input} (Tailwind CSS v4). Do not edit by hand.\n` +
    `export default ${JSON.stringify(body)};\n`;
  writeFileSync(path.join(styles, target.output), js);
  return Buffer.byteLength(body);
}

function compileTarget(target, dir) {
  const out = path.join(dir, target.output);
  const run = spawnSync(process.execPath, [cli, '-i', path.join(styles, target.input), '-o', out, '--minify'], { cwd: root, encoding: 'utf8' });
  if (run.status !== 0) {
    process.stderr.write(run.stderr || run.stdout || 'Tailwind failed\n');
    return false;
  }
  const bytes = writeModule(readFileSync(out, 'utf8'), target);
  console.log(`  tailwind          src/styles/${target.output}  (${(bytes / 1024).toFixed(1)} KB)`);
  return true;
}

function compileGallery() {
  if (!existsSync(GALLERY.input)) return true;
  const run = spawnSync(process.execPath, [cli, '-i', GALLERY.input, '-o', GALLERY.output, '--minify'], { cwd: root, encoding: 'utf8' });
  if (run.status !== 0) {
    process.stderr.write(run.stderr || run.stdout || 'Tailwind failed\n');
    return false;
  }
  console.log(`  tailwind          ${path.relative(root, GALLERY.output).split(path.sep).join('/')}`);
  return true;
}

function compile() {
  const dir = mkdtempSync(path.join(tmpdir(), 'tessel-css-'));
  try {
    return TARGETS.map((t) => compileTarget(t, dir)).every(Boolean) && compileGallery();
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

if (!existsSync(cli)) {
  console.error('Tailwind CLI not found — run `npm install` first.');
  process.exit(1);
}

if (process.argv.includes('--watch')) {
  compile();
  let timer = null;
  for (const dir of ['src/components', 'src/core', 'src/styles', 'gallery']) {
    watch(path.join(root, dir), { recursive: true }, (_, file) => {
      if (!file || file.includes('.generated.')) return;
      clearTimeout(timer);
      timer = setTimeout(compile, 120);
    });
  }
  console.log('Watching src/ for changes…');
} else if (!compile()) {
  process.exit(1);
}
